# Демонстрация команды sqrt (целый корень, округление вниз).
# Исходные значения лежат по адресам 1000..1004, корни - по 1100..1104.

# Заполнение исходных данных
r1 = 1000
r2 = 144
[r1] = r2
r1 = 1001
r2 = 2025
[r1] = r2
r1 = 1002
r2 = 2
[r1] = r2
r1 = 1003
r2 = 0
[r1] = r2
r1 = 1004
r2 = 1000000
[r1] = r2

# Базовые адреса: r0 - исходные данные, r3 - результаты
r0 = 1000
r3 = 1100

# Поэлементно: память[1100 + i] = sqrt(память[1000 + i])
[r3 + 0] = sqrt([r0 + 0])
[r3 + 1] = sqrt([r0 + 1])
[r3 + 2] = sqrt([r0 + 2])
[r3 + 3] = sqrt([r0 + 3])
[r3 + 4] = sqrt([r0 + 4])
